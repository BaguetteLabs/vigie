import Foundation
import Testing
import VigieUI

@testable import ThemeGenKit

@Suite struct ThemeGenTests {
    static let root = URL(filePath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
        .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
    static let designURL = root.appending(path: "docs/ux-designs/ux-vigie-2026-11-04/DESIGN.md")

    static func generate() throws -> [String: String] {
        let markdown = try String(contentsOf: designURL, encoding: .utf8)
        return ThemeGenerator.render(try ThemeGenerator.generate(designMarkdown: markdown))
    }

    @Test func outputIsDeterministic() throws {
        let first = try Self.generate()
        let second = try Self.generate()
        #expect(first == second)
        #expect(first.keys.sorted() == ["base.toml", "chrome-hologram.toml", "twin-metal-tactical.toml"])
    }

    @Test func outputMatchesCheckedInFiles() throws {
        for (name, text) in try Self.generate() {
            let checkedIn = try Data(contentsOf: Self.root.appending(path: "Themes/\(name)"))
            #expect(Data(text.utf8) == checkedIn, "Themes/\(name) is stale: run Scripts/themegen.sh")
        }
    }

    @Test func filesCarrySchemaAndHeader() throws {
        for (_, text) in try Self.generate() {
            #expect(text.hasPrefix("# Generated by themegen from DESIGN.md — do not edit"))
            #expect(text.contains("\nschema = 1\n"))
        }
    }

    @Test func renderedFilesRoundTripThroughTheLoader() throws {
        let markdown = try String(contentsOf: Self.designURL, encoding: .utf8)
        let output = try ThemeGenerator.generate(designMarkdown: markdown)
        let base = try ThemeLoader.decodeBase(Data(ThemeGenerator.render(base: output.base).utf8))
        #expect(base == output.base)
        for variant in output.variants {
            let text = ThemeGenerator.render(variant: variant)
            let decoded = try ThemeLoader.decodeVariant(Data(text.utf8), file: variant.id).get()
            #expect(decoded == variant)
        }
    }

    @Test func prefixesAreStripped() throws {
        let markdown = try String(contentsOf: Self.designURL, encoding: .utf8)
        let output = try ThemeGenerator.generate(designMarkdown: markdown)
        let chrome = try #require(output.variants.first { $0.id == "chrome-hologram" })
        #expect(chrome.looks["dark"]?.colors["surface-panel"] == "#0A0E16")
        #expect(chrome.typography["readout-value"]?.fontWeight == "300")
        #expect(chrome.rounded["card"] == "16px")
        #expect(output.base.rounded["a-card"] == nil)
        #expect(output.base.motion["a-card-iris"] == nil)
        #expect(output.base.colors == ["island": "#000000", "band": "#000000", "shadow": "#000000"])
    }

    @Test func emitterEscapesStrings() {
        let text = TOMLEmitter.emit(
            ["k": .string("a \"q\" \\ b\nc"), "odd key": .string("x")], header: "h")
        #expect(text.contains(#"k = "a \"q\" \\ b\nc""#))
        #expect(text.contains(#""odd key" = "x""#))
    }

    @Test func rejectsBadColors() {
        #expect(throws: ThemeGenerator.GenerationError.invalidColor(key: "a-dark-ink-1", value: "#FFF")) {
            try ThemeGenerator.generate(frontMatter: ["colors": ["a-dark-ink-1": "#FFF"]])
        }
        #expect(throws: ThemeGenerator.GenerationError.unknownVariant(key: "b-dark-ink-1")) {
            try ThemeGenerator.generate(frontMatter: ["colors": ["b-dark-ink-1": "#FFFFFF"]])
        }
    }
}
