import Foundation
import VigieUI
import Yams

/// Generates the built-in theme files from DESIGN.md frontmatter (AD-14), using VigieUI's token types.
public enum ThemeGenerator {
    public enum GenerationError: Error, CustomStringConvertible, Equatable {
        case noFrontMatter
        case invalidFrontMatter(String)
        case unknownVariant(key: String)
        case invalidColor(key: String, value: String)
        case invalidTypography(key: String)

        public var description: String {
            switch self {
            case .noFrontMatter: "DESIGN.md has no YAML frontmatter between two '---' lines"
            case .invalidFrontMatter(let s): "invalid frontmatter: \(s)"
            case .unknownVariant(let key): "token \(key) uses an unknown variant prefix"
            case .invalidColor(let key, let value): "color \(key) = \(value) is not #RRGGBB"
            case .invalidTypography(let key): "typography \(key) lacks fontFamily, fontSize or fontWeight"
            }
        }
    }

    /// DESIGN.md variant prefix -> built-in theme (id, display name).
    public static let variants: [(prefix: String, id: String, name: String)] = [
        ("a", "chrome-hologram", "Chrome Hologram"),
        ("c", "twin-metal-tactical", "Twin Metal Tactical"),
    ]

    public static let header = "Generated by themegen from DESIGN.md — do not edit (AD-14)."

    /// The generated token structs.
    public struct Output: Equatable, Sendable {
        public var base: BaseThemeFile
        public var variants: [ThemeFile]
    }

    /// Extracts the text between the first two `---` lines.
    public static func frontMatter(of markdown: String) throws -> String {
        let lines = markdown.split(separator: "\n", omittingEmptySubsequences: false)
        guard let first = lines.firstIndex(where: { $0.trimmingCharacters(in: .whitespaces) == "---" }),
            let second = lines[(first + 1)...].firstIndex(where: { $0.trimmingCharacters(in: .whitespaces) == "---" })
        else { throw GenerationError.noFrontMatter }
        return lines[(first + 1)..<second].joined(separator: "\n")
    }

    public static func generate(designMarkdown: String) throws -> Output {
        let yaml = try frontMatter(of: designMarkdown)
        guard let root = try Yams.load(yaml: yaml) as? [String: Any] else {
            throw GenerationError.invalidFrontMatter("top level is not a mapping")
        }
        return try generate(frontMatter: root)
    }

    public static func generate(frontMatter root: [String: Any]) throws -> Output {
        var base = BaseThemeFile()
        var files: [String: ThemeFile] = [:]
        for v in variants {
            files[v.prefix] = ThemeFile(id: v.id, name: v.name, extends: baseThemeID)
        }

        func variantPrefix(of key: String) -> String? {
            variants.first { key.hasPrefix($0.prefix + "-") }?.prefix
        }

        // Colors: base-<role> | <v>-<look>-<role>.
        for (key, value) in try stringMap(root["colors"], name: "colors") {
            guard isHexColor(value) else { throw GenerationError.invalidColor(key: key, value: value) }
            let hex = value.uppercased()
            if key.hasPrefix("base-") {
                base.colors[String(key.dropFirst(5))] = hex
                continue
            }
            guard let prefix = variantPrefix(of: key) else { throw GenerationError.unknownVariant(key: key) }
            let rest = key.dropFirst(prefix.count + 1)
            guard let look = Look.allCases.first(where: { rest.hasPrefix($0.rawValue + "-") }) else {
                throw GenerationError.unknownVariant(key: key)
            }
            let role = String(rest.dropFirst(look.rawValue.count + 1))
            files[prefix]!.looks[look.rawValue, default: LookTokens(colors: [:])].colors[role] = hex
        }

        // Typography: <v>-<role> only (variant-specific).
        for (key, value) in try nestedStringMap(root["typography"], name: "typography") {
            guard let prefix = variantPrefix(of: key) else { throw GenerationError.unknownVariant(key: key) }
            guard let family = value["fontFamily"], let size = value["fontSize"], let weight = value["fontWeight"]
            else { throw GenerationError.invalidTypography(key: key) }
            files[prefix]!.typography[String(key.dropFirst(prefix.count + 1))] = TypographyToken(
                fontFamily: family, fontSize: size, fontWeight: weight,
                lineHeight: value["lineHeight"], letterSpacing: value["letterSpacing"])
        }

        // Rounded and motion: shared keys in base, <v>- keys in the variant (prefix stripped).
        func split(_ table: String) throws -> (shared: [String: String], byVariant: [String: [String: String]]) {
            var shared: [String: String] = [:]
            var byVariant: [String: [String: String]] = [:]
            for (key, value) in try stringMap(root[table], name: table) {
                if let prefix = variantPrefix(of: key) {
                    byVariant[prefix, default: [:]][String(key.dropFirst(prefix.count + 1))] = value
                } else {
                    shared[key] = value
                }
            }
            return (shared, byVariant)
        }
        let rounded = try split("rounded")
        let motion = try split("motion")
        base.rounded = rounded.shared
        base.motion = motion.shared
        for v in variants {
            files[v.prefix]!.rounded = rounded.byVariant[v.prefix] ?? [:]
            files[v.prefix]!.motion = motion.byVariant[v.prefix] ?? [:]
        }

        base.spacing = try stringMap(root["spacing"], name: "spacing")
        base.components = try nestedStringMap(root["components"], name: "components")

        return Output(base: base, variants: variants.map { files[$0.prefix]! })
    }

    // MARK: Rendering

    /// File name -> TOML text, for every generated file.
    public static func render(_ output: Output) -> [String: String] {
        var files = ["base.toml": render(base: output.base)]
        for variant in output.variants {
            files["\(variant.id).toml"] = render(variant: variant)
        }
        return files
    }

    public static func render(base: BaseThemeFile) -> String {
        var root: [String: TOMLNode] = [
            "schema": .integer(base.schema),
            "id": .string(base.id),
            "name": .string(base.name),
            "colors": table(base.colors),
            "rounded": table(base.rounded),
            "spacing": table(base.spacing),
            "motion": table(base.motion),
        ]
        root["components"] = .table(base.components.mapValues(table))
        return TOMLEmitter.emit(root, header: header, leadingKeys: ["schema", "id", "name"])
    }

    public static func render(variant: ThemeFile) -> String {
        var root: [String: TOMLNode] = [
            "schema": .integer(variant.schema),
            "id": .string(variant.id),
            "name": .string(variant.name),
        ]
        if let extends = variant.extends { root["extends"] = .string(extends) }
        if !variant.rounded.isEmpty { root["rounded"] = table(variant.rounded) }
        if !variant.motion.isEmpty { root["motion"] = table(variant.motion) }
        root["typography"] = .table(
            variant.typography.mapValues { token in
                var t: [String: String] = [
                    "fontFamily": token.fontFamily, "fontSize": token.fontSize, "fontWeight": token.fontWeight,
                ]
                t["lineHeight"] = token.lineHeight
                t["letterSpacing"] = token.letterSpacing
                return table(t)
            })
        root["looks"] = .table(variant.looks.mapValues { .table(["colors": table($0.colors)]) })
        return TOMLEmitter.emit(root, header: header, leadingKeys: ["schema", "id", "name", "extends"])
    }

    private static func table(_ map: [String: String]) -> TOMLNode {
        .table(map.mapValues { .string($0) })
    }

    // MARK: YAML helpers

    static func isHexColor(_ s: String) -> Bool {
        s.count == 7 && s.first == "#" && s.dropFirst().allSatisfy(\.isHexDigit)
    }

    static func scalarString(_ value: Any) -> String? {
        switch value {
        case let s as String: s
        case let i as Int: String(i)
        case let d as Double: String(d)
        case let b as Bool: b ? "true" : "false"
        default: nil
        }
    }

    static func stringMap(_ value: Any?, name: String) throws -> [String: String] {
        guard let value else { return [:] }
        guard let map = value as? [String: Any] else {
            throw GenerationError.invalidFrontMatter("\(name) is not a map")
        }
        var out: [String: String] = [:]
        for (k, v) in map {
            guard let s = scalarString(v) else {
                throw GenerationError.invalidFrontMatter("\(name).\(k) is not a scalar")
            }
            out[k] = s
        }
        return out
    }

    static func nestedStringMap(_ value: Any?, name: String) throws -> [String: [String: String]] {
        guard let value else { return [:] }
        guard let map = value as? [String: Any] else {
            throw GenerationError.invalidFrontMatter("\(name) is not a map")
        }
        var out: [String: [String: String]] = [:]
        for (k, v) in map { out[k] = try stringMap(v, name: "\(name).\(k)") }
        return out
    }
}

/// `themegen --design <DESIGN.md> --out <Themes dir> [--resources <dir>]`.
public enum ThemeGenCommand {
    public static func run(arguments: [String]) throws {
        var design: String?
        var outs: [String] = []
        var iterator = arguments.makeIterator()
        while let arg = iterator.next() {
            switch arg {
            case "--design": design = iterator.next()
            case "--out", "--resources": if let v = iterator.next() { outs.append(v) }
            case "-h", "--help":
                print("usage: themegen --design <DESIGN.md> --out <Themes dir> [--resources <dir>]")
                return
            default: throw CommandError.usage("unknown argument \(arg)")
            }
        }
        guard let design, !outs.isEmpty else {
            throw CommandError.usage("usage: themegen --design <DESIGN.md> --out <Themes dir> [--resources <dir>]")
        }
        let markdown = try String(contentsOf: URL(filePath: design), encoding: .utf8)
        let files = ThemeGenerator.render(try ThemeGenerator.generate(designMarkdown: markdown))
        for dir in outs {
            let folder = URL(filePath: dir, directoryHint: .isDirectory)
            try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
            for (name, text) in files {
                try Data(text.utf8).write(to: folder.appending(path: name), options: .atomic)
            }
            print("themegen: wrote \(files.keys.sorted().joined(separator: ", ")) to \(dir)")
        }
    }

    public enum CommandError: Error, CustomStringConvertible {
        case usage(String)
        public var description: String {
            switch self {
            case .usage(let s): s
            }
        }
    }
}
